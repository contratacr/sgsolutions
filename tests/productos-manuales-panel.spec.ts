import {test,expect} from '@playwright/test';
import {readFile,writeFile,unlink} from 'node:fs/promises';
import base from '../src/lib/catalogo-base.json';
import fotos from '../src/lib/imagenes-productos-verificadas.json';
import {esquemaCatalogo} from '../src/lib/catalogo-modelo';
import es from '../messages/es.json';import en from '../messages/en.json';
const archivo='.privado/contenido-pruebas/catalogo.json';
test.afterEach(async()=>{await unlink(archivo).catch(()=>{});});
for(const idioma of ['es','en'] as const)test('creación manual, destacado, calendario y precio en carrito '+idioma,async({page,context},info)=>{
 const t=(idioma==='es'?es:en).AdminCatalogo,u=(idioma==='es'?es:en).AdminUX,m=(idioma==='es'?es:en).AdminImagenes;
 const c=esquemaCatalogo.parse(base),foto=fotos.find(f=>c.productos.some(p=>p.publicado&&p.id===f.id))!,ejemplo={...c.productos.find(p=>p.id===foto.id)!,imagen:foto.imagen};c.productos=[];
 await writeFile(archivo,JSON.stringify({contenido:c,revision:1}),{mode:0o600});
 const {token}=JSON.parse(await readFile('.privado/contenido-pruebas/sesion.json','utf8'));
 await context.addCookies([{name:'sg-admin-local',value:token,domain:'127.0.0.1',path:'/'},{name:'sg-idioma',value:idioma,domain:'127.0.0.1',path:'/'}]);
 await page.route('https://**/*',route=>route.abort());
 await page.goto('/panel/catalogo');await page.getByRole('button',{name:t.agregarProducto,exact:true}).click();
 const editor=page.locator('.admin-producto-editor');
 await editor.getByLabel(`${t.nombre} (${u.idiomaEs})`,{exact:true}).fill(ejemplo.nombre.es);
 await editor.getByLabel(`${t.nombre} (${u.idiomaEn})`,{exact:true}).fill(ejemplo.nombre.en);
 await editor.getByLabel(`${t.descripcionCampo} (${u.idiomaEs})`,{exact:true}).fill('Producto de prueba aislada.');
 await editor.getByLabel(`${t.descripcionCampo} (${u.idiomaEn})`,{exact:true}).fill('Isolated test product.');
 await editor.getByLabel(t.marca,{exact:true}).fill(ejemplo.marca);
 await editor.getByLabel(t.codigoFabricante,{exact:true}).fill(ejemplo.codigoFabricante);
 await expect(editor.getByLabel(t.ofertaInicio,{exact:true})).toBeEnabled();
 await expect(editor.getByLabel(t.ofertaFin,{exact:true})).toBeEnabled();
 await expect(editor.locator('.admin-oferta-prioridad input')).toHaveCount(0);
 await editor.getByLabel(t.precioManual,{exact:false}).fill('25000');await editor.getByLabel(t.existenciasManuales,{exact:false}).fill('5');
 await editor.getByLabel(t.precioDescuento,{exact:false}).fill('20000');
 await editor.getByLabel(t.ofertaInicio,{exact:true}).fill('2020-01-01T09:00');
 await editor.getByLabel(t.ofertaFin,{exact:true}).fill('2099-01-01T09:00');
 await expect(editor.getByRole('combobox',{name:t.disponibilidadManual,exact:true})).toBeDisabled();
 await editor.locator('.gestor-url summary').click();await editor.getByLabel(m.url,{exact:true}).fill(ejemplo.imagen);await editor.getByRole('button',{name:m.agregarUrl,exact:true}).click();
 await editor.getByLabel(t.destacado,{exact:true}).check();await editor.getByLabel(t.publicado,{exact:true}).check();
 await editor.screenshot({path:info.outputPath('editor-manual-'+idioma+'.png')});
 await page.locator('.admin-actions button').first().click();
 await expect.poll(async()=>JSON.parse(await readFile(archivo,'utf8')).revision).toBe(2);
 const guardado=JSON.parse(await readFile(archivo,'utf8')).contenido.productos.find((p:{origen?:string})=>p.origen==='manual');
 expect(guardado).toMatchObject({publicado:true,destacado:true,precioManual:25000,precioDescuento:20000,ofertaInicio:'2020-01-01T15:00:00.000Z',ofertaFin:'2099-01-01T15:00:00.000Z'});
 await page.reload();await expect(page.locator('html')).toHaveAttribute('lang',idioma);
 await page.goto('/tienda?q='+encodeURIComponent(ejemplo.codigoFabricante));
 const tarjeta=page.locator('.shop-producto').filter({has:page.locator(`h3 a[href*="${guardado.slug}"]`)});
 await expect(tarjeta).toHaveCount(1);await expect(tarjeta.locator('.producto-descuento [aria-hidden=true]')).toHaveText('−20%');await expect(tarjeta.locator('.shop-precio del')).toContainText('25');await expect(tarjeta.locator('.shop-precio strong')).toContainText('20');
 await tarjeta.locator('h3 a').click();await expect(page.locator('.ficha-precio del')).toContainText('25');
 await page.locator('.ficha-agregar').click();await page.locator('.carrito-confirmacion').getByRole('button',{name:idioma==='es'?'Ver carrito':'View cart',exact:true}).click();
 await expect(page.locator('.carrito-resumen>div>strong').last()).toHaveText('₡20\u00a0000');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:info.outputPath('carrito-manual-'+idioma+'.png'),fullPage:true});
 const headers={origin:'http://127.0.0.1:3124','cf-connecting-ip':guardado.id};
 const datos={idioma,articulos:[{id:guardado.id,cantidad:2,precio:20000}]};
 const aprobacion=await page.request.post('/api/compra/verificar',{headers,data:datos});expect(aprobacion.status()).toBe(200);
 const acceso=await aprobacion.json();expect(acceso.token).toBeTruthy();
 const verificaciones=JSON.parse(await readFile('.privado/contenido-pruebas/asesorias.json','utf8'));
 expect(verificaciones.find((p:{id:string})=>p.id===acceso.id).articulos[0]).toMatchObject({cantidad:2,producto:{id:guardado.id,precio:20000}});
 const snapshot=JSON.parse(await readFile(archivo,'utf8'));snapshot.contenido.productos.find((p:{id:string})=>p.id===guardado.id).ofertaFin='2021-01-01T15:00:00.000Z';
 await writeFile(archivo,JSON.stringify(snapshot),{mode:0o600});
 const vencida=await page.request.post('/api/compra/verificar',{headers,data:datos});expect(vencida.status()).toBe(409);expect(await vencida.json()).toMatchObject({error:'catalogo_actualizado'});
});
