import {test,expect} from '@playwright/test';
for(const idioma of ['es','en'])test('favoritos sin ingreso, vista previa y carrito '+idioma,async({page,context,baseURL})=>{
 await context.addCookies([{name:'sg-idioma',value:idioma,url:baseURL!}]);
 await page.goto('/tienda');await page.locator('#buscar-equipo').fill('FXXDCFH1001C');
 const tarjeta=page.locator('.shop-producto').filter({hasText:'FXXDCFH1001C'});
 await expect(tarjeta).toBeVisible();await expect(tarjeta.locator('button.producto-agregar')).toBeEnabled();
 await expect(page.locator('.shop-orden-trigger')).toBeEnabled();await tarjeta.hover();
 const corazon=tarjeta.locator('[aria-pressed]');await expect(corazon).toBeEnabled();await corazon.click();
 await expect(page.locator('.favoritos-confirmacion')).toContainText(idioma==='es'?'Guardado en favoritos':'Saved to favorites');
 await expect(page.locator('.favoritos-confirmacion-ver')).toHaveAttribute('href','/favoritos');
 await expect(page.locator('.favoritos-confirmacion-ingresar')).toHaveCount(0);await expect(corazon).toHaveAttribute('aria-pressed','true');
 await page.reload();await expect(page.locator('#buscar-equipo')).toHaveValue('FXXDCFH1001C');
 await expect(tarjeta).toBeVisible();await tarjeta.hover();await expect(corazon).toHaveAttribute('aria-pressed','true');
 const lupa=tarjeta.locator('.producto-accion').nth(1);await lupa.click();
 const modal=page.getByRole('dialog');await expect(modal).toBeVisible();await modal.locator('input[type=number]').fill('2');
 await modal.locator('.boton-azul').click();await expect(modal).not.toBeVisible();
 await expect(page.locator('.carrito-confirmacion')).toBeVisible();
 expect(JSON.parse(await page.evaluate(()=>localStorage.getItem('sg-carrito-v1'))||'[]')[0].cantidad).toBe(2);
 await page.keyboard.press('Escape');await expect(modal).not.toBeVisible();await expect(lupa).toBeFocused();
 await page.goto('/favoritos');await expect(page.locator('.favoritos-grid .shop-producto')).toHaveCount(1);
 await page.locator('.favoritos-grid .shop-producto').hover();await page.locator('.favoritos-grid [aria-pressed]').click();
 await expect(page.locator('.favoritos-grid .shop-producto')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
