import {test,expect} from '@playwright/test';
import es from '../messages/es.json';import en from '../messages/en.json';
for(const idioma of ['es','en'] as const)test(`Primer paso reúne facturación, contacto y dirección ${idioma}`,async({page,context,baseURL})=>{
 const t=(idioma==='es'?es:en).Compra;
 await context.addCookies([{name:'sg-idioma',value:idioma,url:baseURL!}]);
 await page.goto('/tienda');await expect(page.locator('.shop-orden-trigger')).toBeEnabled();await page.locator('.shop-producto button').first().click();await page.goto('/pagar');
 const nav=page.getByRole('navigation',{name:t.pasosCompra,exact:true});
 await expect(nav.getByRole('button')).toHaveCount(3);
 await expect(page.locator('[data-compra-paso="1"]')).toBeHidden();
 await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();
 await expect(page.locator('[data-compra-paso="0"]')).toBeVisible();
 await page.locator('[name=nombre]').fill('Ana');await page.locator('[name=apellidos]').fill('Prueba');await page.locator('[name=correo]').fill('qa@example.com');await page.locator('.campo-telefono:has(input[name=telefono]) input[type=tel]').fill('88888888');
 await page.getByRole('radio',{name:t.clienteJuridico,exact:true}).check();
 await page.locator('[name=razonSocial]').fill('Empresa de prueba');
 await page.locator('[name=identificacion]').fill('3101951810');
 await page.getByRole('checkbox',{name:t.facturaElectronicaOpcional,exact:true}).check();
 await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();
 await expect(page.locator('[data-compra-paso="0"]')).toBeVisible();
 await page.locator('[name=correoFactura]').fill('qa@example.com');await page.locator('[name=direccionFiscal]').fill('Atenas');
 await page.locator('input[name=modalidad][value=envio]').check();
 await page.locator('[name=provincia]').selectOption('Alajuela');await page.locator('[name=canton]').selectOption('Atenas');await page.locator('[name=distrito]').selectOption('Atenas');
 await page.locator('[name=provincia]').selectOption('Heredia');await expect(page.locator('[name=canton]')).toHaveValue('');await expect(page.locator('[name=distrito]')).toHaveValue('');
 await page.locator('[name=provincia]').selectOption('Alajuela');await page.locator('[name=canton]').selectOption('Atenas');await page.locator('[name=distrito]').selectOption('Atenas');await page.locator('[name=direccion]').fill('Centro de Atenas');
 await expect(page.getByRole('checkbox',{name:t.crearCuentaOpcion,exact:true})).toHaveCount(0);
 await expect(page.locator('.compra-crear-cuenta')).toHaveCount(0);
 await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();
 await expect(page.locator('[data-compra-paso="1"]')).toBeVisible();
 await expect(page.locator('[name=notas]')).toBeHidden();
 await page.getByRole('checkbox',{name:t.agregarNotas,exact:true}).check();
 await page.locator('[name=notas]').fill('Nota de ejemplo');
 await page.getByRole('checkbox',{name:t.agregarNotas,exact:true}).uncheck();
 await expect(page.locator('[name=notas]')).toBeDisabled();
 await page.getByRole('checkbox',{name:t.agregarNotas,exact:true}).check();
 await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();
 await expect(page.locator('[data-compra-paso="2"]')).toBeVisible();
 await nav.getByRole('button').first().click();
 await expect(page.locator('[name=nombre]')).toHaveValue('Ana');
 await expect(page.locator('[name=razonSocial]')).toHaveValue('Empresa de prueba');
 await expect(page.locator('[name=distrito]')).toHaveValue('Atenas');
 await nav.getByRole('button').nth(1).click();await expect(page.locator('[name=notas]')).toHaveValue('Nota de ejemplo');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
