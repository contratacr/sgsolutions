import {test,expect} from '@playwright/test';
import es from '../messages/es.json';import en from '../messages/en.json';
for(const idioma of ['es','en'] as const)test(`tarjeta abre Tilopay directamente y conserva pedido al volver ${idioma}`,async({page,context,baseURL})=>{
 const t=(idioma==='es'?es:en).Compra;
 await context.addCookies([{name:'sg-idioma',value:idioma,url:baseURL!}]);let verificaciones=0,inicios=0;
 const destino='https://secure.tilopay.com/qa-payment';
 await page.route(destino,r=>r.fulfill({contentType:'text/html',body:'<h1>Tilopay QA</h1>'}));
 await page.route('**/api/compra/verificar',async ruta=>{verificaciones++;await ruta.fulfill({json:{id:'qa',token:'qa'}});});
 await page.route('**/api/pagos/tilopay/iniciar',async ruta=>{inicios++;await ruta.fulfill({json:{url:destino,pedido:'00000000-0000-4000-8000-000000000099'}});});
 await page.goto('/tienda');await page.locator('#buscar-equipo').fill('conector');await page.locator('#buscar-equipo').press('Enter');await expect(page.locator('.shop-producto button.producto-agregar').first()).toBeVisible();await expect(page.locator('.shop-orden-trigger')).toBeEnabled();await page.locator('.shop-producto').first().hover();await page.locator('.producto-agregar').first().click();await expect(page.locator('.carrito-cantidad')).toHaveText('1');await page.goto('/pagar');
 await page.locator('[name=nombre]').fill('Cliente');await page.locator('[name=apellidos]').fill('QA');await page.locator('[name=correo]').fill('cliente@example.com');await page.locator('[name=identificacion]').fill('123456789');await page.locator('.campo-telefono input[type=tel]').fill('88888888');
 await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();await page.getByRole('button',{name:t.pasoSiguiente,exact:true}).click();
 await page.locator('input[value=tarjeta]').check();await page.locator('[name=consentimiento]').check();
 await expect(page.locator('[id^=tlpy_],#responseTilopay')).toHaveCount(0);
 const navegaciones:string[]=[];
 page.on('framenavigated',f=>{if(f===page.mainFrame())navegaciones.push(f.url());});
 await page.locator('.compra-acciones-finales button[type=submit]').click();
 await expect(page).toHaveURL(destino);expect(navegaciones).toEqual([destino]);
 expect(verificaciones).toBe(1);expect(inicios).toBe(1);
 await page.goBack();await expect(page).toHaveURL(/\/pagar$/);
 await expect(page.locator('.carrito-cantidad')).toHaveText('1');
 await expect(page.locator('.compra-pasos [aria-current=step]')).toContainText('03.');
 await expect(page.locator('[name=nombre]')).toHaveValue('Cliente');
 await expect(page.locator('[name=correo]')).toHaveValue('cliente@example.com');
 await page.reload();await expect(page.locator('[name=nombre]')).toHaveValue('Cliente');
 await page.locator('[name=consentimiento]').check();
 await page.locator('.compra-acciones-finales button[type=submit]').click();
 await expect(page).toHaveURL(destino);expect(inicios).toBe(1);
});
