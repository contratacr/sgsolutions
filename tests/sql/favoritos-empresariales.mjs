import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {PGlite}=await import(process.env.SG_PGLITE_MODULE??'@electric-sql/pglite');
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create function public.cuenta_habilitada() returns boolean language sql stable as $$select coalesce(current_setting('test.habilitada',true),'1')='1'$$;
grant usage on schema auth,public to authenticated;`);
for(const file of ['20261014000200_favoritos.sql','20261016000100_favoritos_empresariales.sql'])await db.exec(await readFile('supabase/migrations/'+file,'utf8'));
const propio='00000000-0000-4000-8000-000000000001',ajeno='00000000-0000-4000-8000-000000000002';
await db.query('insert into auth.users values($1),($2)',[propio,ajeno]);
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[propio]);await db.exec('set role authenticated');
for(const id of ['eurocomp-producto-real','empresa-intcomex-nw608ubq18'])await db.query('insert into favoritos(usuario_id,producto_id) values($1,$2)',[propio,id]);
assert.equal((await db.query('select * from favoritos')).rows.length,2);
await assert.rejects(db.query('insert into favoritos(usuario_id,producto_id) values($1,$2)',[ajeno,'empresa-intcomex-nw608ubq18']));
await assert.rejects(db.query('insert into favoritos(usuario_id,producto_id) values($1,$2)',[propio,'otro-proveedor-123']));
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[ajeno]);
assert.equal((await db.query('select * from favoritos')).rows.length,0);
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[propio]);
await db.exec("select set_config('test.habilitada','0',false)");
assert.equal((await db.query('select * from favoritos')).rows.length,0);
await assert.rejects(db.query('insert into favoritos(usuario_id,producto_id) values($1,$2)',[propio,'empresa-intcomex-otro']));
await db.close();console.log('Favoritos empresariales y Eurocomp válidos; RLS rechaza otras cuentas, cuentas bloqueadas e identidades ajenas.');
