import {test,expect} from '@playwright/test';
import {readFile,writeFile,unlink} from 'node:fs/promises';
import base from '../src/lib/catalogo-base.json';
import {esquemaCatalogo} from '../src/lib/catalogo-modelo';
import es from '../messages/es.json';import en from '../messages/en.json';
const archivo='.privado/contenido-pruebas/catalogo.json';
test.afterEach(async()=>{await unlink(archivo).catch(()=>{});});
for(const idioma of ['es','en'] as const)test('fechas parciales no se borran ni se guardan incompletas '+idioma,async({page,context})=>{
 const t=(idioma==='es'?es:en).AdminCatalogo,c=esquemaCatalogo.parse(base),p=c.productos.find(p=>p.publicado&&p.codigoEurocomp)!;
 p.precioManual=25000;p.precioDescuento=20000;p.ofertaInicio=null;p.ofertaFin=null;c.productos=[p];
 await writeFile(archivo,JSON.stringify({contenido:c,revision:1}),{mode:0o600});
 const {token}=JSON.parse(await readFile('.privado/contenido-pruebas/sesion.json','utf8'));
 await context.addCookies([{name:'sg-admin-local',value:token,domain:'127.0.0.1',path:'/'},{name:'sg-idioma',value:idioma,domain:'127.0.0.1',path:'/'}]);
 await context.route('https://**/*',r=>r.abort());
 await page.goto('/panel/catalogo');await page.locator('.admin-producto-fila button').first().click();
 const campo=page.getByLabel(t.ofertaInicio,{exact:false});await expect(campo).toBeEnabled();
 await campo.focus();for(let i=0;i<8;i++)await campo.press('ArrowLeft');await campo.press('1');
 await expect.poll(()=>campo.evaluate((e:HTMLInputElement)=>e.validity.badInput)).toBe(true);
 await page.locator('.admin-actions button').first().click();
 expect(JSON.parse(await readFile(archivo,'utf8')).revision).toBe(1);
 await campo.fill('2026-11-15T09:00');
 await page.getByLabel(t.ofertaFin,{exact:true}).fill('2026-12-15T09:00');
 await page.locator('.admin-actions button').first().click();
 await expect.poll(async()=>JSON.parse(await readFile(archivo,'utf8')).revision).toBe(2);
 const guardado=JSON.parse(await readFile(archivo,'utf8')).contenido.productos[0];
 expect(guardado.ofertaInicio).toBe('2026-11-15T15:00:00.000Z');expect(guardado.ofertaFin).toBe('2026-12-15T15:00:00.000Z');
 await page.reload();await page.locator('.admin-producto-fila button').first().click();
 await expect(page.getByLabel(t.ofertaInicio,{exact:false})).toHaveValue('2026-11-15T09:00');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
