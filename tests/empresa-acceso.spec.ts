import {test,expect} from '@playwright/test';
for(const idioma of ['es','en'])test(`categoría empresarial solo en filtros y controles ordenados ${idioma}`,async({page,context,baseURL},info)=>{
 await context.addCookies([{name:'sg-idioma',value:idioma,url:baseURL!}]);await page.goto('/tienda');
 await expect(page.locator('#buscar-equipo')).toBeEnabled();
 await expect(page.locator('.shop-empresa-entrada')).toHaveCount(0);
 const cabecera=page.locator('.shop-resultados-cabecera');
 await expect(cabecera.getByRole('button',{name:idioma==='es'?'Soluciones Empresariales':'Business Solutions',exact:true})).toHaveCount(0);
 const asesor=cabecera.locator('.shop-asesoria-inline');await expect(asesor).toHaveCount(1);
 await expect(asesor).toHaveAttribute('target','_blank');await expect(asesor).toHaveAttribute('rel','noopener noreferrer');
 const movil=/movil|mobile/.test(info.project.name);
 if(movil)await page.locator('.shop-abrir-filtros').click();
 const panel=page.locator(movil?'.shop-panel-filtros':'.shop-sidebar');
 const categoria=panel.locator('.shop-categoria-empresa>button');await categoria.click();
 await expect(categoria).toHaveAttribute('aria-expanded','true');
 await expect(panel.locator('.shop-categoria-empresa .shop-subcategorias button')).toHaveCount(5);
 if(movil)await panel.locator('.shop-panel-filtros-acciones>.boton').first().click();
 await expect(page.locator('.shop-resultados')).toHaveAttribute('aria-busy','false');
 await expect(page.locator('.shop-filtros-activos')).toContainText(idioma==='es'?'Soluciones Empresariales':'Business Solutions');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 const solapados=await cabecera.evaluate(e=>{const nodos=[...e.querySelectorAll(':scope>.shop-orden,:scope>.shop-asesoria-inline,:scope>.shop-abrir-filtros,.conteo')].map(n=>n.getBoundingClientRect()).filter(r=>r.width&&r.height);return nodos.some((a,i)=>nodos.slice(i+1).some(b=>a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top));});
 expect(solapados).toBe(false);
 await page.screenshot({path:`.privado/tienda-controles-${info.project.name}-${idioma}.png`});
 await page.reload();await expect(page.locator('html')).toHaveAttribute('lang',idioma);
 await expect(page.locator('#buscar-equipo')).toBeEnabled();
 await expect(page.locator('.shop-filtros-activos')).toContainText(idioma==='es'?'Soluciones Empresariales':'Business Solutions');
});
